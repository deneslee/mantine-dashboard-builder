import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { parse } from 'yaml';

/**
 * Checks the planning files under docs/ and writes the generated parts.
 * Rules: .agents/skills/planning/SKILL.md. Run from the repo root:
 *   node scripts/plan-index.mjs          write docs/roadmap.md, docs/decisions/README.md, milestone indexes
 *   node scripts/plan-index.mjs --check  exit 1 if a file is invalid or a generated part is out of date
 *   node scripts/plan-index.mjs --next T print the next free id (M, T, R or ADR)
 */

const DOCS = 'docs';
const MILESTONES = join(DOCS, 'milestones');
const RESEARCH = join(DOCS, 'research');
const DECISIONS = join(DOCS, 'decisions');
const ROADMAP = join(DOCS, 'roadmap.md');
const DECISION_INDEX = join(DECISIONS, 'README.md');
const START = '<!-- plan:index:start -->';
const END = '<!-- plan:index:end -->';
const NOTICE = '<!-- Generated by scripts/plan-index.mjs. Do not edit. -->';

const STATUS = {
  milestone: ['proposed', 'planned', 'in-progress', 'blocked', 'done', 'dropped'],
  task: ['proposed', 'planned', 'in-progress', 'blocked', 'done', 'dropped'],
  research: ['open', 'concluded', 'abandoned'],
  adr: ['open', 'proposed', 'accepted', 'rejected', 'deferred', 'superseded'],
};
const PATTERN = {
  milestone: /^M(\d+)-[a-z0-9-]+$/,
  task: /^T(\d+)-[a-z0-9-]+\.md$/,
  research: /^R(\d+)-[a-z0-9-]+\.md$/,
  adr: /^ADR-(\d{4})-[a-z0-9-]+\.md$/,
};

const errors = [];
const posix = (path) => path.split('\\').join('/');
const list = (dir) => (existsSync(dir) ? readdirSync(dir, { withFileTypes: true }) : []);
const byNumber = (a, b) => a.number - b.number;

const frontmatter = (path) => {
  const match = /^---\r?\n([\s\S]*?)\r?\n---/.exec(readFileSync(path, 'utf8'));
  if (!match) {
    errors.push(`${posix(path)}: no frontmatter`);
    return {};
  }
  try {
    return parse(match[1]) ?? {};
  } catch (error) {
    errors.push(`${posix(path)}: frontmatter is not valid YAML (${error.message.split('\n')[0]})`);
    return {};
  }
};

const load = (kind, path, name, extra = {}) => {
  const match = PATTERN[kind].exec(name);
  if (!match) {
    errors.push(`${posix(path)}: name must match ${PATTERN[kind]}`);
    return null;
  }
  const data = frontmatter(kind === 'milestone' ? join(path, 'README.md') : path);
  const expected = kind === 'adr' ? `ADR-${match[1]}` : `${name[0]}${Number(match[1])}`;
  if (data.id !== expected) errors.push(`${posix(path)}: id must be ${expected}, found ${data.id}`);
  if (!data.title) errors.push(`${posix(path)}: title missing`);
  if (!STATUS[kind].includes(data.status)) {
    errors.push(`${posix(path)}: status "${data.status}" is not one of ${STATUS[kind].join(', ')}`);
  }
  return { ...data, ...extra, kind, path, number: Number(match[1]) };
};

const milestones = [];
const tasks = [];
const research = [];

for (const entry of list(MILESTONES)) {
  if (!entry.isDirectory()) continue;
  const dir = join(MILESTONES, entry.name);
  const milestone = load('milestone', dir, entry.name);
  if (!milestone) continue;
  milestones.push(milestone);
  for (const file of list(dir)) {
    if (!file.isFile() || file.name === 'README.md') continue;
    const kind = file.name.startsWith('T') ? 'task' : 'research';
    const item = load(kind, join(dir, file.name), file.name, { milestone: milestone.id });
    if (item) (kind === 'task' ? tasks : research).push(item);
  }
}
for (const file of list(RESEARCH)) {
  if (!file.isFile()) continue;
  const item = load('research', join(RESEARCH, file.name), file.name);
  if (item) research.push(item);
}
const adrs = list(DECISIONS)
  .filter((file) => file.isFile() && file.name !== 'README.md')
  .map((file) => load('adr', join(DECISIONS, file.name), file.name))
  .filter(Boolean);

const all = [...milestones, ...tasks, ...research, ...adrs];
const ids = new Map();
for (const item of all) {
  if (ids.has(item.id))
    errors.push(`${item.id}: used by ${posix(ids.get(item.id).path)} and ${posix(item.path)}`);
  ids.set(item.id, item);
}
for (const item of all) {
  for (const ref of [...(item.depends_on ?? []), ...(item.leads_to ?? [])]) {
    if (!ids.has(ref)) errors.push(`${posix(item.path)}: unknown id ${ref}`);
  }
  if (item.milestone && !ids.has(item.milestone))
    errors.push(`${posix(item.path)}: unknown milestone ${item.milestone}`);
}

const next = process.argv[process.argv.indexOf('--next') + 1];
if (process.argv.includes('--next')) {
  const pool = { M: milestones, T: tasks, R: research, ADR: adrs }[next];
  if (!pool) throw new Error('Use --next M, T, R or ADR');
  const number = Math.max(0, ...pool.map((item) => item.number)) + 1;
  process.stdout.write(`${next === 'ADR' ? `ADR-${String(number).padStart(4, '0')}` : `${next}${number}`}\n`);
  process.exit(0);
}

if (errors.length) {
  process.stderr.write(`Planning files have errors:\n${errors.map((error) => `- ${error}`).join('\n')}\n`);
  process.exit(1);
}

const link = (from, item) => {
  const target = item.kind === 'milestone' ? join(item.path, 'README.md') : item.path;
  return `[${item.id} ${item.title}](${posix(relative(from, target))})`;
};
const line = (from, item) => `- ${link(from, item)}: ${item.status}`;
const section = (title, lines) => (lines.length ? [`## ${title}`, lines.join('\n')] : []);

const roadmap = () => {
  const parts = ['# Roadmap', NOTICE];
  const rows = milestones.sort(byNumber).flatMap((milestone) => {
    const own = (pool) => pool.filter((item) => item.milestone === milestone.id).sort(byNumber);
    return [
      line(DOCS, milestone),
      ...[...own(tasks), ...own(research)].map((item) => `  ${line(DOCS, item)}`),
    ];
  });
  parts.push(...section('Milestones', rows));
  parts.push(
    ...section(
      'Shared research',
      research
        .filter((item) => !item.milestone)
        .sort(byNumber)
        .map((item) => line(DOCS, item)),
    ),
  );
  return `${parts.join('\n\n')}\n`;
};

const decisionIndex = () => {
  const parts = ['# Decisions', NOTICE];
  for (const status of STATUS.adr) {
    const items = adrs.filter((item) => item.status === status).sort(byNumber);
    parts.push(
      ...section(
        status,
        items.map((item) => `- ${link(DECISIONS, item)}${item.milestone ? ` (${item.milestone})` : ''}`),
      ),
    );
  }
  return `${parts.join('\n\n')}\n`;
};

const milestoneBlock = (milestone) => {
  const own = (pool) => pool.filter((item) => item.milestone === milestone.id).sort(byNumber);
  const parts = [
    ...section(
      'Tasks',
      own(tasks).map((item) => line(milestone.path, item)),
    ),
    ...section(
      'Research',
      own(research).map((item) => line(milestone.path, item)),
    ),
    ...section(
      'Decisions',
      own(adrs).map((item) => line(milestone.path, item)),
    ),
  ];
  return [START, NOTICE, ...parts, END].join('\n\n');
};

const outputs = [
  [ROADMAP, roadmap()],
  [DECISION_INDEX, decisionIndex()],
  ...milestones.map((milestone) => {
    const path = join(milestone.path, 'README.md');
    const text = readFileSync(path, 'utf8');
    const start = text.indexOf(START);
    const end = text.indexOf(END);
    const base = start === -1 ? `${text.trimEnd()}\n\n` : text.slice(0, start);
    const rest = end === -1 ? '\n' : text.slice(end + END.length);
    return [path, `${base}${milestoneBlock(milestone)}${rest}`];
  }),
];

const stale = outputs.filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text);
if (process.argv.includes('--check')) {
  if (stale.length) {
    process.stderr.write(
      `Out of date, run node scripts/plan-index.mjs:\n${stale.map(([path]) => `- ${posix(path)}`).join('\n')}\n`,
    );
    process.exit(1);
  }
} else {
  for (const [path, text] of stale) writeFileSync(path, text);
  process.stdout.write(`Planning index: ${stale.length} file(s) updated.\n`);
}
